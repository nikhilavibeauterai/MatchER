const { chromium } = require("playwright-core");
const { BASE, LINK, LIB, OUT } = process.env;
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await (await browser.newContext({ viewport: { width: 1400, height: 860 } })).newPage();
  const problems = [];
  page.on("pageerror", (e) => problems.push(`pageerror: ${e.message}`));
  page.on("dialog", (d) => d.accept());
  await page.goto(LINK);
  await page.click('.mode-card[data-mode="me"]');
  await page.fill("#path", LIB);
  await page.click("#use-path");
  await page.waitForSelector("#an-go", { timeout: 300000 });
  await page.click("#an-go");
  await page.waitForSelector(".journey");
  const res = {};
  await page.goto(BASE + "/#draw?sort=1");
  await page.waitForSelector("#dtop img");
  const look = () => page.$eval("#dtop img", (i) => ({ filter: i.style.filter || "", fit: i.style.objectFit || "contain" }));
  res.start = await look();
  await page.keyboard.press("f");
  await page.waitForTimeout(500);
  res.afterF = await look();
  await page.keyboard.press("c");
  await page.waitForTimeout(300);
  res.afterC = await look();
  await page.click("#open-menu");
  await page.waitForSelector("#menu[open]");
  res.menu = await page.$$eval("#menu .menu-list > *", (x) => x.map((e) => e.textContent.replace(/\s+/g, " ").trim()).filter((t) => /Auto-/.test(t)));
  await page.click('[data-m="filter"]');
  await page.waitForTimeout(300);
  res.afterMenuFilter = await look();
  console.log(JSON.stringify({ ...res, problems }));
  await browser.close();
})().catch((e) => { console.error("FAILED:", e.message); process.exit(1); });
